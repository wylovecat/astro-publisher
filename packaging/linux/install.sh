#!/usr/bin/env bash
# Install (or remove) astro-publisher from an unpacked tarball.
#
# Where things go, and why there:
#
#   ~/.local/bin/                 the binaries, first on PATH for a normal login
#                                 shell on both Debian/Ubuntu and Fedora
#   ~/.local/share/applications/  the .desktop entry the launcher reads, with no
#                                 root and no /usr write
#   ~/.config/astro-publisher/    where the app itself puts config.toml and its
#                                 single-instance lock
#
# Nothing here needs root. `--system` is offered for a machine-wide install
# (/usr/local), which does.
#
# Usage:
#   ./install.sh                 install into ~/.local
#   ./install.sh --prefix DIR    install into DIR/bin + DIR/share
#   ./install.sh --system        install into /usr/local (needs sudo)
#   ./install.sh --uninstall     remove what a previous run installed

set -euo pipefail

here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
prefix="${XDG_DATA_HOME:-$HOME/.local}"
system=0
uninstall=0

while [ $# -gt 0 ]; do
  case "$1" in
    --prefix) prefix="$2"; shift 2 ;;
    --system) system=1; prefix=/usr/local; shift ;;
    --uninstall) uninstall=1; shift ;;
    -h|--help) sed -n '2,20p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

bin_dir="$prefix/bin"
apps_dir="$prefix/share/applications"
icon_dir="$prefix/share/icons/hicolor/scalable/apps"
icon_file="$icon_dir/astro-publisher.svg"
desktop_file="$apps_dir/astro-publisher.desktop"
launcher="$prefix/share/applications/astro-publisher-launcher.sh"
manifest="$bin_dir/.astro-publisher-install"

as_root() {
  if [ "$(id -u)" -eq 0 ]; then
    "$@"
  elif command -v sudo >/dev/null 2>&1; then
    sudo "$@"
  else
    echo "this install needs root and sudo is not available" >&2
    exit 1
  fi
}

if [ "$uninstall" -eq 1 ]; then
  for binary in astro-publisher astro-publisher-core astro-publisher-mcp; do
    [ -e "$bin_dir/$binary" ] && as_root rm -f "$bin_dir/$binary"
  done
  [ -e "$desktop_file" ] && as_root rm -f "$desktop_file"
  [ -e "$launcher" ] && as_root rm -f "$launcher"
  [ -e "$icon_file" ] && as_root rm -f "$icon_file"
  [ -e "$manifest" ] && as_root rm -f "$manifest"
  command -v update-desktop-database >/dev/null 2>&1 && as_root update-desktop-database "$apps_dir" || true
  echo "removed the binaries and the launcher entry"
  echo "your settings are left alone: ~/.config/astro-publisher (delete it by hand if you want them gone)"
  exit 0
fi

for binary in astro-publisher astro-publisher-core astro-publisher-mcp; do
  if [ ! -f "$here/bin/$binary" ]; then
    echo "missing $here/bin/$binary - is this an unpacked tarball?" >&2
    exit 1
  fi
done
[ -f "$here/astro-publisher.desktop" ] || {
  echo "missing $here/astro-publisher.desktop - is this an unpacked tarball?" >&2
  exit 1
}

version="$(cat "$here/VERSION" 2>/dev/null || echo unknown)"
as_root mkdir -p "$bin_dir" "$apps_dir" "$icon_dir"
for binary in astro-publisher astro-publisher-core astro-publisher-mcp; do
  as_root cp "$here/bin/$binary" "$bin_dir/$binary"
  as_root chmod 755 "$bin_dir/$binary"
done

[ -f "$here/astro-publisher.svg" ] && {
  as_root cp "$here/astro-publisher.svg" "$icon_file"
  as_root chmod 644 "$icon_file"
}

# The .desktop file carries Exec=astro-publisher, which resolves against PATH.
# That breaks for a `--prefix` install that is not on PATH (a desktop session
# does not read the shell's rc files), so the entry points at a launcher script
# that hard-codes the absolute path instead.
{
  echo '#!/bin/sh'
  echo '# Generated by astro-publisher install.sh - absolute path, so it works'
  echo '# even when the install prefix is not on the desktop session PATH.'
  echo "exec \"$bin_dir/astro-publisher\" \"\$@\""
} >"$launcher"
as_root chmod 755 "$launcher"

sed -e "s|@LAUNCHER@|$launcher|g" -e "s|@VERSION@|$version|g" \
  "$here/astro-publisher.desktop" >"$desktop_file"
as_root chmod 644 "$desktop_file"

if command -v update-desktop-database >/dev/null 2>&1; then
  as_root update-desktop-database "$apps_dir" || true
fi

printf 'installed: astro-publisher %s\nprefix: %s\nremoved by: %s --uninstall\n' \
  "$version" "$prefix" "$0" >"$manifest"
as_root chmod 644 "$manifest"

cat <<EOF

astro-publisher $version installed.

  desktop entry : $desktop_file
  config        : \${XDG_CONFIG_HOME:-\$HOME/.config}/astro-publisher/astro-publisher/config.toml

If this was a --prefix or --system install and '$bin_dir' is not already on
PATH, add it:
  export PATH="$bin_dir:\$PATH"

First run: open 文章 or 新建章节 from the launcher. The repository path can be
set on the 设置 page, or with ASTRO_PUBLISHER_REPO.
EOF
